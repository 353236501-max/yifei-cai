export type StudyMode = 'lesson' | 'practice';
export function studyTask(mode: StudyMode): string {
  const basis='优先依据服务端提供的内置复习资料决定讲解范围，无需用户导入PDF。逐项标注参考文件名与物理页码，并明确内置资料是原创整理和延伸，不是PDF原文。可选本地摘录出现公式断裂、题干缺失或考点不匹配时，不能自行补造原题；仍可使用完整内置资料继续讲解。无直接对应内容的知识点可参考相关资料作原创补充，明确哪些为延伸，禁止伪造来源。所有数学公式用$...$或独立行$$...$$包围，矩阵用bmatrix，分式用\\frac，上下标加花括号；避免Unicode拼接公式。';
  return basis+(mode==='lesson'
    ? '以考研强化复习为目标，按资料实际覆盖的知识点梳理：概念及直觉、适用条件与反例、公式之间的推导、题型识别线索、方法选择与替代解法、关键步骤、常见失误、关联考点和复习自测清单。给出有完整条件和分步解析的原创综合例题，再给两道有答案的迁移练习；难度体现在条件辨析、方法组合、参数讨论或边界情况，不只替换数字。证据不足时缩小范围并说明，不靠堆砌基础定义凑数。'
    : '先概述资料中的考点与方法链，设计两道原创改编题：一道强化题，一道综合迁移题。改变条件、问法或情境，不仅替换数字。各题给出来源依据、与资料的变化、完整题干、所需知识点、难度理由、渐进提示、参考答案、分步推导、条件检查和易错点。数学题需有实际推理步骤；408题需明确数据规模、系统假设、单位和边界。不能将生成答案声称为经过 Lean 或数值验证。');
}
